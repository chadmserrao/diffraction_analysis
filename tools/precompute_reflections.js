// Precompute reflection lists for every library phase (uses the same crystal.js as the app).
// usage: node tools/precompute_reflections.js [dMinNm]
const fs = require('fs'), path = require('path');
globalThis.DP = {};
for (const f of ['crystal.js', 'library_data.js']) (0, eval)(fs.readFileSync(path.join(__dirname, '..', 'src', f), 'utf8'));
const C = DP.crystal, CS = ['triclinic', 'monoclinic', 'orthorhombic', 'tetragonal', 'trigonal', 'hexagonal', 'cubic'];
const dMin = parseFloat(process.argv[2] || '0.07');
const out = {}; let t0 = Date.now(), slow = [];
DP.LIBRARY_ROWS.forEach((r, idx) => {
  const [id, formula, sg, cs, eh, theo, lat, sitesFlat] = r;
  const sites = []; for (let i = 0; i < sitesFlat.length; i += 4) sites.push({ el: sitesFlat[i], f: sitesFlat.slice(i + 1, i + 4) });
  const st = { id, crystalSystem: CS[cs], lattice: [lat.slice(0, 3), lat.slice(3, 6), lat.slice(6, 9)], sites };
  const t = Date.now();
  const cv = C.conventionalize(st);
  const refl = C.reflections(cv, dMin, { minI: 0.01 }).slice(0, 32);
  const p = C.params(cv.lattice);
  out[id] = { c: [p.a, p.b, p.c, p.alpha, p.beta, p.gamma].map((v) => +v.toFixed(4)), n: cv.indexNote ? 1 : 0,
    r: refl.map((q) => [+q.d.toFixed(5), +q.I.toFixed(3), q.hkl[0], q.hkl[1], q.hkl[2], q.mult, +q.Ispot.toFixed(3)]) };
  const dt = Date.now() - t; if (dt > 2000) slow.push([formula, dt]);
  if (idx % 500 === 0) console.error(idx, (Date.now() - t0) / 1000 + 's');
});
const js = '// Auto-generated by tools/precompute_reflections.js (dMin ' + dMin + ' nm). Do not edit.\n(function (DP) {\n  DP.LIBRARY_REFL = ' + JSON.stringify(out) + ';\n})(typeof globalThis !== "undefined" ? (globalThis.DP = globalThis.DP || {}) : {});\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'library_refl.js'), js);
console.error('done', Object.keys(out).length, (js.length / 1e6).toFixed(2) + ' MB', (Date.now() - t0) / 1000 + 's', 'slow:', slow.slice(0, 10));
