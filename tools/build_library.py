#!/usr/bin/env python3
"""Build the offline phase library embedded in the web app from the Materials Project API.

Usage:  MP_API_KEY=... python3 tools/build_library.py      (or put MP_API_KEY in diffraction_tool/.env)
Writes src/library_data.js. Standard library only.
"""
import itertools, json, os, sys, time, urllib.parse, urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

CORE = ['H', 'Li', 'B', 'C', 'N', 'O', 'F', 'Na', 'Si', 'P', 'S', 'Cl', 'K', 'Se']
METALS = ['Mg', 'Al', 'Ca', 'Ti', 'V', 'Cr', 'Mn', 'Fe', 'Co', 'Ni', 'Cu', 'Zn', 'Ga', 'Ge', 'Sr', 'Y', 'Zr',
          'Nb', 'Mo', 'Ru', 'Rh', 'Pd', 'Ag', 'Cd', 'In', 'Sn', 'Sb', 'Te', 'Cs', 'Ba', 'La', 'Ce', 'Hf',
          'Ta', 'W', 'Pt', 'Au', 'Pb', 'Bi', 'Rb']
ALL = CORE + METALS
FIELDS = 'material_id,formula_pretty,symmetry,energy_above_hull,theoretical,structure'
CS = {'Triclinic': 0, 'Monoclinic': 1, 'Orthorhombic': 2, 'Tetragonal': 3, 'Trigonal': 4, 'Hexagonal': 5, 'Cubic': 6}


def key():
    k = os.environ.get('MP_API_KEY')
    envf = os.path.join(ROOT, '.env')
    if not k and os.path.exists(envf):
        for line in open(envf):
            if line.startswith('MP_API_KEY='):
                k = line.split('=', 1)[1].strip()
    if not k:
        sys.exit('Set MP_API_KEY or create diffraction_tool/.env')
    return k


def get(params, k):
    url = 'https://api.materialsproject.org/materials/summary/?' + urllib.parse.urlencode(params)
    for attempt in range(5):
        try:
            req = urllib.request.Request(url, headers={'X-API-KEY': k, 'accept': 'application/json', 'User-Agent': 'tem-diffraction-annotator/1.0'})
            with urllib.request.urlopen(req, timeout=120) as r:
                return json.load(r)
        except Exception as e:  # retry on transient errors
            if attempt == 4:
                raise
            time.sleep(2 * (attempt + 1))


def chemsys_list():
    out = [e for e in ALL]
    out += ['-'.join(sorted(p)) for p in itertools.combinations(ALL, 2)]
    out += ['-'.join(sorted(t)) for t in itertools.combinations(CORE, 3)]
    return out


def keep(d):
    eh = d.get('energy_above_hull') or 0
    return (not d.get('theoretical') and eh <= 0.1) or eh <= 0.02


def main():
    k = key()
    systems = chemsys_list()
    print(len(systems), 'chemical systems', file=sys.stderr)
    phases = {}
    for i in range(0, len(systems), 40):
        batch = systems[i:i + 40]
        skip = 0
        while True:
            res = get({'chemsys': ','.join(batch), 'energy_above_hull_max': 0.1, '_fields': FIELDS,
                       '_limit': 1000, '_skip': skip}, k)
            data = res.get('data', [])
            for d in data:
                if keep(d):
                    phases[d['material_id']] = d
            if len(data) < 1000:
                break
            skip += 1000
        print(f'{i + len(batch)}/{len(systems)} systems, {len(phases)} phases', file=sys.stderr)
    rows = []
    for mid, d in sorted(phases.items(), key=lambda kv: kv[1]['formula_pretty']):
        st = d['structure']
        sites = []
        ok = True
        for s in st['sites']:
            sp = s['species']
            if len(sp) != 1:  # skip disordered sites
                ok = False
                break
            sites += [sp[0]['element'], *[round(x % 1.0, 4) for x in s['abc']]]
        if not ok:
            continue
        lat = [round(x, 4) for row in st['lattice']['matrix'] for x in row]
        rows.append([mid, d['formula_pretty'], d['symmetry']['symbol'], CS.get(d['symmetry']['crystal_system'], 0),
                     round(d.get('energy_above_hull') or 0, 3), 1 if d.get('theoretical') else 0, lat, sites])
    meta = {'source': 'Materials Project (api.materialsproject.org)', 'built': time.strftime('%Y-%m-%d'),
            'elements': ALL, 'count': len(rows),
            'filter': 'experimentally observed with E_hull <= 0.1 eV/atom, or E_hull <= 0.02 eV/atom'}
    js = ('// Auto-generated by tools/build_library.py. Do not edit by hand.\n'
          '(function (DP) {\n  DP.LIBRARY_META = ' + json.dumps(meta) + ';\n  DP.LIBRARY_ROWS = ' +
          json.dumps(rows, separators=(',', ':')) + ';\n})(typeof globalThis !== "undefined" ? (globalThis.DP = globalThis.DP || {}) : {});\n')
    out = os.path.join(ROOT, 'src', 'library_data.js')
    open(out, 'w').write(js)
    print('wrote', out, len(rows), 'phases', round(len(js) / 1e6, 2), 'MB', file=sys.stderr)


if __name__ == '__main__':
    main()
